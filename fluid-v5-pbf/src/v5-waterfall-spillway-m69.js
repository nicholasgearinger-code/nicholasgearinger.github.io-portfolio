// Fluid V5 M6.9 physical spillway wrapper.
// Reuses the M6.8 terrain/reservoir architecture but removes the last residual prescribed inlet
// velocity. The pump only relocates lower-pool water into the submerged rear reservoir; pressure,
// gravity and collisions must create every bit of subsequent motion.

const url=new URL('./v5-waterfall-spillway-m68.js',import.meta.url);
const r=await fetch(url,{cache:'no-store'});
if(!r.ok)throw new Error(`Fluid V5 M6.9: unable to load M6.8 spillway source (${r.status}).`);
let src=await r.text();

const oldY='let y=floorY+d*(2.0+h2*8.5);';
const newY='let y=floorY+d*(1.35+h2*3.25);';
if(!src.includes(oldY))throw new Error('Fluid V5 M6.9 rear-reservoir placement signature changed.');
src=src.replace(oldY,newY);

const oldV='V[i]=vec4<f32>(0.022+h0*.020,0.0,(h1-.5)*.008,0.0);';
const newV='V[i]=vec4<f32>(0.0,0.0,0.0,0.0);';
if(!src.includes(oldV))throw new Error('Fluid V5 M6.9 recirculation velocity signature changed.');
src=src.replace(oldV,newV);

// The recirculation rate may vary, but relocated water begins at rest below the rear free surface.
// This makes the pump a mass-conservation mechanism rather than a waterfall force.
src=src.replace('A slow natural pump surge changes reservoir head over several seconds; it never acts on the fall.',
 'The pump varies only returned volume. Relocated water starts submerged and at rest; it never imparts waterfall momentum.');

src=src.replaceAll('M6.8','M6.9').replaceAll('M68','M69').replaceAll('m68','m69');
const blob=URL.createObjectURL(new Blob([src],{type:'text/javascript'}));
try{await import(blob);}finally{URL.revokeObjectURL(blob);}
if(window.__v5WaterfallM69){window.__v5WaterfallM68=window.__v5WaterfallM69;window.__v5WaterfallM68.backend='neutral-pump-physical-spillway-m69';window.__v5WaterfallM68.neutralPump=true;}
console.info('[Fluid V5 M6.9] recirculation is mass-only; waterfall momentum is generated by pressure + gravity.');
